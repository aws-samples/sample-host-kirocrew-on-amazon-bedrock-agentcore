#!/usr/bin/env python3
"""Build runtime/pin-manifest.txt from an strace of the image's start.

Run the image's smoke under ``strace -f -e trace=openat,execve -o trace.log``
(see docs/operations.md, "Runtime V2 page pin"), then:

    python tools/pin_manifest.py trace.log > runtime/pin-manifest.txt

Architecture-specific path parts become ``{machine}`` / ``{node_arch}`` so one
manifest serves both image architectures. The embedding model is left out: it
is large, loaded off the readiness path, and would add its size to every
restored session.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

_OPEN = re.compile(r'(?:openat\([^,]+,|execve\()\s*"([^"]+)"')
_SKIP_PREFIXES = (  # paths the trace saw that are not image files to pin
    "/proc",
    "/sys",
    "/dev",
    "/tmp",  # noqa: S108 - a prefix to skip, never written
    "/mnt/workspace",
    "/etc",
    "/opt/kirocrew/models",
)
# Only what the start itself reads. kiro-cli and the KAS engine start with the
# first chat; pinning them (about 370 MB) made the V2 snapshot build exceed the
# platform's health check while the image disk is still fetched lazily.
_EXTRA: tuple[str, ...] = ()


def normalize(path: str) -> str:
    path = re.sub(r"linux-x64\b", "linux-{node_arch}", path)
    return path.replace("x86_64", "{machine}")


def build(trace: str) -> list[str]:
    paths: set[str] = set()
    for line in trace.splitlines():
        match = _OPEN.search(line)
        if match is not None and "ENOENT" not in line:
            path = match.group(1)
        elif line.startswith("/"):
            # A plain path list (one path per line) is accepted too.
            path = line.strip()
        else:
            continue
        if path.startswith(_SKIP_PREFIXES) or path.endswith("/"):
            continue
        paths.add(normalize(path))
    return sorted(paths) + list(_EXTRA)


def main(argv: list[str]) -> int:
    lines = build(Path(argv[1]).read_text(encoding="utf-8", errors="replace"))
    sys.stdout.write("# Generated by tools/pin_manifest.py; see runtime/.../page_pin.py.\n")
    sys.stdout.write("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
